// Mantém a maiúscula inicial que o utilizador usou.
const sameCase = (original, text) => (original[0] === original[0].toUpperCase() ? text[0].toUpperCase() + text.slice(1) : text);

export function displayName(name) {
  const key = normalize(name);
  const found = state.lang === "EN" ? PT_TO_EN[key] : EN_TO_PT[key];
  return found ? sameCase(name, found) : name;
}
